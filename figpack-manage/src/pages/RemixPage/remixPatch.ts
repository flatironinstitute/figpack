// Remix patches. A remix patch carries the changes a remix makes to a
// figure's spec, keyed by the figure's structure (child names and props)
// rather than by the code that built the figure, so that it can be applied
// when the figure is generated again in Python (view.save(..., remix=...))
// or uploaded on the remix page of another figure. Format (version 1):
//
//   {
//     "figpack_remix_patch": 1,
//     "source": { "figureUrl": "...", "createdAt": "2026-10-23T12:00:00.000Z" },
//     "patch": <spec diff>
//   }
//
// The spec diff has the shape of a spec node, {data?, view_type?, props?,
// children?}, with only what differs between the figure's original spec and
// the remixed one: props whose values changed (whole values, so a changed
// list such as `items` is given in full, as in the spec), `data` and
// `view_type` where changed, and children (by name) that differ. A child that
// is new in the remix is given in full. Props or children removed by the
// remix are not recorded: in a spec generated by figpack they only repeat the
// zarr attributes, so removing them has no effect. See docs/remix_patches.md.

export type SpecNode = {
  data?: string | null;
  view_type?: string;
  props?: { [key: string]: unknown };
  children?: { [name: string]: SpecNode };
};

export const REMIX_PATCH_VERSION = 1;

export type RemixPatch = {
  figpack_remix_patch: number;
  source?: { figureUrl?: string; createdAt?: string };
  patch: SpecNode;
};

const isObject = (x: unknown): x is Record<string, unknown> =>
  !!x && typeof x === "object" && !Array.isArray(x);

export const deepEqual = (a: unknown, b: unknown): boolean => {
  if (a === b) return true;
  if (Array.isArray(a) || Array.isArray(b)) {
    return (
      Array.isArray(a) &&
      Array.isArray(b) &&
      a.length === b.length &&
      a.every((x, i) => deepEqual(x, b[i]))
    );
  }
  if (!isObject(a) || !isObject(b)) return false;
  const ka = Object.keys(a);
  const kb = Object.keys(b);
  return (
    ka.length === kb.length && ka.every((k) => k in b && deepEqual(a[k], b[k]))
  );
};

// The changes from `original` to `remixed`, as a spec diff ({} if none)
export const diffSpec = (original: SpecNode, remixed: SpecNode): SpecNode => {
  const diff: SpecNode = {};
  if ("data" in remixed && !deepEqual(original.data, remixed.data)) {
    diff.data = remixed.data;
  }
  if ("view_type" in remixed && original.view_type !== remixed.view_type) {
    diff.view_type = remixed.view_type;
  }
  const props: { [key: string]: unknown } = {};
  for (const [key, value] of Object.entries(remixed.props || {})) {
    if (!deepEqual(original.props?.[key], value)) props[key] = value;
  }
  if (Object.keys(props).length) diff.props = props;
  const children: { [name: string]: SpecNode } = {};
  for (const [name, child] of Object.entries(remixed.children || {})) {
    const d = diffSpec(original.children?.[name] || {}, child);
    if (Object.keys(d).length) children[name] = d;
  }
  if (Object.keys(children).length) diff.children = children;
  return diff;
};

export const makeRemixPatch = (
  original: SpecNode,
  remixed: SpecNode,
  figureUrl: string,
): RemixPatch => ({
  figpack_remix_patch: REMIX_PATCH_VERSION,
  source: { figureUrl, createdAt: new Date().toISOString() },
  patch: diffSpec(original, remixed),
});

// One line per changed part of a spec diff, such as "item_0/series_1:
// props.color", for showing what a patch contains
export const describeSpecDiff = (diff: SpecNode, path = ""): string[] => {
  const where = path || "root";
  const lines: string[] = [];
  if ("data" in diff) lines.push(`${where}: data`);
  if ("view_type" in diff) lines.push(`${where}: view_type`);
  const props = Object.keys(diff.props || {});
  if (props.length) {
    lines.push(`${where}: ${props.map((p) => `props.${p}`).join(", ")}`);
  }
  for (const [name, child] of Object.entries(diff.children || {})) {
    lines.push(...describeSpecDiff(child, path ? `${path}/${name}` : name));
  }
  return lines;
};

// File name for a downloaded patch: "<title>-remix.json"
export const patchFileName = (title: string | undefined) => {
  const slug = (title || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
  return `${slug || "figure"}-remix.json`;
};

export const pythonSnippet = (fileName: string) =>
  `# Apply the remix when making the figure (needs figpack newer than 0.4.0)
view.show(title="...", remix="${fileName}")
# or
view.save("figure_dir", title="...", remix="${fileName}")`;
